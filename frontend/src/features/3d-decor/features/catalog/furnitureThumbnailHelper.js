/**
 * Lấy URL ảnh Isometric của một vật thể nội thất
 * @param {string} modelPath - Đường dẫn model (ví dụ: '/furniture/seating.glb')
 * @param {'NW' | 'NE' | 'SE' | 'SW'} [angle='NW'] - Góc nhìn Isometric (mặc định NW - góc nhìn tối ưu nhất)
 * @returns {string|null} URL ảnh Isometric (ví dụ: '/isometric/loungeSofa_NW.png')
 */
export function getFurnitureThumbnail(modelPath, angle = 'NW') {
  if (!modelPath) return null;
  const cleanPath = modelPath.startsWith('/') ? modelPath : '/' + modelPath;
  const fileName = cleanPath.split('/').pop();
  const kenneyBase = MODEL_TO_KENNEY_MAP[cleanPath] || MODEL_TO_KENNEY_MAP['/furniture/' + fileName] || fileName.replace(/\.[^/.]+$/, '');
  return `/isometric/${kenneyBase}_${angle}.png`;
}
